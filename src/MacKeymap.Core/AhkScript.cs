using System.Text;

namespace MacKeymap.Core;

/// <summary>
/// Compiles the active profile into an AutoHotkey v2 script. Rule resolution is done here with
/// <see cref="Profile.PreviewRules"/>, so what the preview page shows is exactly what runs.
/// </summary>
/// <remarks>
/// Application-dependent behavior is precomputed per "context": one for every application pattern the
/// profile mentions plus a default. At runtime the script picks the context from the foreground
/// window's process: an exact full-path pattern first, then the EXE name, else the default. That
/// mirrors <see cref="Profile.AppMatches"/>, so results are identical to the preview.
/// </remarks>
public static class AhkScript
{
    public sealed record Result(string Script, int HotkeyCount, IReadOnlyList<string> Skipped);

    private const string DefaultContext = "default";
    private const string NoMatchApp = "\u0001";

    public static Result Generate(Profile profile)
    {
        var skipped = new List<string>();
        var patterns = profile.AppModes.Select(a => a.App)
            .Concat(Profile.Lines(profile.Exclusions))
            .Concat(profile.Overrides.SelectMany(r => Profile.Lines(r.Apps)))
            .Select(Profile.Normalize).Where(p => p.Length > 0).Distinct().ToList();

        var actions = new List<(string Kind, string Value)>();
        var contexts = new List<(string Id, Dictionary<string, int> Map)>();
        var contextBySignature = new Dictionary<string, string>();
        var pathCtx = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var nameCtx = new SortedDictionary<string, string>(StringComparer.Ordinal);

        string ContextFor(string app)
        {
            var map = new Dictionary<string, int>();
            foreach (var rule in profile.PreviewRules(app))
            {
                var hk = Hotkey(rule.Trigger);
                var action = Action(rule, hk);
                if (hk == null || action == null)
                {
                    if (hk == null || action is null && !IsIdentity(rule))
                        skipped.Add($"{rule.Name}（{rule.Trigger} → {rule.Value}）");
                    continue;
                }
                if (map.ContainsKey(hk)) continue; // PreviewRules is already priority ordered
                var idx = actions.IndexOf(action.Value);
                if (idx < 0) { actions.Add(action.Value); idx = actions.Count - 1; }
                map[hk] = idx + 1; // AHK arrays are 1-based
            }
            var signature = string.Join(";", map.OrderBy(kv => kv.Key, StringComparer.Ordinal).Select(kv => $"{kv.Key}={kv.Value}"));
            if (contextBySignature.TryGetValue(signature, out var existing)) return existing;
            var id = contexts.Count == 0 ? DefaultContext : $"c{contexts.Count}";
            contexts.Add((id, map));
            contextBySignature[signature] = id;
            return id;
        }

        ContextFor(NoMatchApp);
        foreach (var p in patterns)
        {
            var id = ContextFor(p);
            if (id == DefaultContext) continue;
            if (p.Contains('\\')) pathCtx[p] = id; else nameCtx[p] = id;
        }
        // Rules skipped once per context would repeat; report each distinct one.
        var distinctSkipped = skipped.Distinct().ToList();

        var hotkeys = contexts.SelectMany(c => c.Map.Keys).Distinct().Order(StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.AppendLine("; Generated by Mac Keymap. Do not edit: this file is rewritten whenever settings are saved.");
        sb.AppendLine($"; Profile: {profile.Name.Replace('\n', ' ')}");
        sb.AppendLine("#Requires AutoHotkey v2.0");
        sb.AppendLine("#SingleInstance Force");
        sb.AppendLine("#UseHook");
        sb.AppendLine("Persistent");
        sb.AppendLine("KeyHistory 0");
        sb.AppendLine("ListLines false");
        sb.AppendLine("A_MenuMaskKey := \"vkE8\" ; keeps a lone Alt/Win from opening the menu bar or Start");
        sb.AppendLine($"A_IconTip := {Str("Mac Keymap：" + profile.Name)}");
        sb.AppendLine();
        sb.AppendLine("Actions := [");
        foreach (var (kind, value) in actions) sb.AppendLine($"    [{Str(kind)}, {Str(value)}],");
        sb.AppendLine("]");
        sb.AppendLine("Contexts := Map()");
        foreach (var (id, map) in contexts)
        {
            sb.Append($"Contexts[{Str(id)}] := Map(");
            sb.Append(string.Join(", ", map.OrderBy(kv => kv.Key, StringComparer.Ordinal).Select(kv => $"{Str(kv.Key)}, {kv.Value}")));
            sb.AppendLine(")");
        }
        sb.AppendLine("PathCtx := Map(" + string.Join(", ", pathCtx.Select(kv => $"{Str(kv.Key)}, {Str(kv.Value)}")) + ")");
        sb.AppendLine("NameCtx := Map(" + string.Join(", ", nameCtx.Select(kv => $"{Str(kv.Key)}, {Str(kv.Value)}")) + ")");
        sb.AppendLine("Hotkeys := [" + string.Join(", ", hotkeys.Select(Str)) + "]");
        sb.AppendLine("""

            CurrentContext() {
                try path := StrLower(StrReplace(WinGetProcessPath("A"), "/", "\"))
                catch
                    return "default"
                if PathCtx.Has(path)
                    return PathCtx[path]
                SplitPath path, &name
                return NameCtx.Has(name) ? NameCtx[name] : "default"
            }

            Lookup(hk) {
                ctx := Contexts[CurrentContext()]
                return ctx.Has(hk) ? ctx[hk] : 0
            }

            Fire(hk) {
                i := Lookup(hk)
                if !i
                    return
                a := Actions[i]
                switch a[1] {
                    case "send": Send a[2]
                    case "text": SendText a[2]
                    case "run":
                        try Run a[2]
                    case "caps": SetCapsLockState !GetKeyState("CapsLock", "T")
                }
            }

            ; A hotkey only exists for the foreground app when its context maps it; otherwise the key passes through.
            HotIf (hk) => Lookup(hk) > 0
            for hk in Hotkeys
                Hotkey hk, Fire
            HotIf
            """);
        return new Result(sb.ToString(), hotkeys.Count, distinctSkipped);
    }

    private static readonly Dictionary<string, string> HotkeyModifiers = new(StringComparer.OrdinalIgnoreCase)
    {
        ["LCtrl"] = "<^", ["RCtrl"] = ">^", ["Ctrl"] = "^",
        ["LAlt"] = "<!", ["RAlt"] = ">!", ["Alt"] = "!",
        ["LWin"] = "<#", ["RWin"] = ">#", ["Win"] = "#",
        ["LShift"] = "<+", ["RShift"] = ">+", ["Shift"] = "+",
    };

    private static readonly Dictionary<string, string> SendModifiers = new(StringComparer.OrdinalIgnoreCase)
    {
        ["LCtrl"] = "LCtrl", ["Ctrl"] = "LCtrl", ["RCtrl"] = "RCtrl",
        ["LAlt"] = "LAlt", ["Alt"] = "LAlt", ["RAlt"] = "RAlt",
        ["LWin"] = "LWin", ["Win"] = "LWin", ["RWin"] = "RWin",
        ["LShift"] = "LShift", ["Shift"] = "LShift", ["RShift"] = "RShift",
    };

    private static readonly Dictionary<string, string> NamedKeys = new(StringComparer.OrdinalIgnoreCase)
    {
        ["Left"] = "Left", ["Right"] = "Right", ["Up"] = "Up", ["Down"] = "Down",
        ["Tab"] = "Tab", ["Enter"] = "Enter", ["Backspace"] = "Backspace", ["Delete"] = "Delete",
        ["Insert"] = "Insert", ["Space"] = "Space", ["Home"] = "Home", ["End"] = "End",
        ["PageUp"] = "PgUp", ["PageDown"] = "PgDn", ["Esc"] = "Escape", ["Escape"] = "Escape",
        ["CapsLock"] = "CapsLock",
        ["["] = "[", ["]"] = "]", [";"] = ";", ["'"] = "'", [","] = ",", ["."] = ".",
        ["/"] = "/", ["\\"] = "\\", ["-"] = "-", ["="] = "=", ["`"] = "`",
    };

    /// <summary>Key token → AHK key name, or null if unsupported.</summary>
    private static string? Key(string token)
    {
        if (token.Length == 1 && char.IsAsciiLetterOrDigit(token[0])) return token.ToLowerInvariant();
        if (NamedKeys.TryGetValue(token, out var named)) return named;
        if (token.Length is >= 2 and <= 3 && (token[0] is 'F' or 'f') && int.TryParse(token[1..], out var f) && f is >= 1 and <= 24) return $"F{f}";
        if (token.StartsWith("Num", StringComparison.OrdinalIgnoreCase) && token.Length == 4 && char.IsAsciiDigit(token[3])) return $"Numpad{token[3]}";
        return null;
    }

    private static (List<string> Mods, string Key)? Parse(string combo)
    {
        var tokens = combo.Split('+', StringSplitOptions.TrimEntries);
        // A trailing empty token means the key itself is "+", which no rule uses; treat as unsupported.
        if (tokens.Length == 0 || tokens.Any(t => t.Length == 0)) return null;
        var mods = tokens[..^1].ToList();
        return (mods, tokens[^1]);
    }

    /// <summary>Resolved physical trigger (e.g. "LAlt+Shift+C") → AHK hotkey (e.g. "<!+c").</summary>
    public static string? Hotkey(string trigger)
    {
        if (Parse(trigger) is not { } parsed) return null;
        var (mods, keyToken) = parsed;
        if (mods.Any(m => !HotkeyModifiers.ContainsKey(m))) return null;
        if (Key(keyToken) is not string key) return null;
        // Canonical modifier order so equivalent triggers produce the same hotkey.
        var prefix = string.Concat(mods.Select(m => HotkeyModifiers[m]).Distinct().Order(StringComparer.Ordinal));
        return prefix + key;
    }

    /// <summary>"LCtrl+Shift+C" → "{LCtrl down}{LShift down}{c}{LShift up}{LCtrl up}".</summary>
    public static string? SendKeys(string combo)
    {
        if (Parse(combo) is not { } parsed) return null;
        var (mods, keyToken) = parsed;
        if (mods.Any(m => !SendModifiers.ContainsKey(m))) return null;
        if (Key(keyToken) is not string key) return null;
        var down = mods.Select(m => SendModifiers[m]).Distinct().ToList();
        return string.Concat(down.Select(m => $"{{{m} down}}")) + $"{{{key}}}" + string.Concat(Enumerable.Reverse(down).Select(m => $"{{{m} up}}"));
    }

    /// <summary>A shortcut that sends exactly its own trigger (e.g. LAlt+Tab while LAlt is Command) is left to Windows.</summary>
    private static bool IsIdentity(Rule r) =>
        r.Action is RuleAction.Shortcut or RuleAction.Language && Hotkey(r.Trigger) is string a && Hotkey(r.Value) is string b && a == b;

    private static (string, string)? Action(Rule r, string? hotkey)
    {
        if (hotkey == null || IsIdentity(r)) return null;
        switch (r.Action)
        {
            case RuleAction.Text: return r.Value.Length == 0 ? null : ("text", r.Value);
            case RuleAction.Launch: return r.Value.Trim().Length == 0 ? null : ("run", r.Value.Trim());
            default:
                if (string.Equals(r.Value.Trim(), "CapsLock", StringComparison.OrdinalIgnoreCase)) return ("caps", "");
                return SendKeys(r.Value) is string keys ? ("send", keys) : null;
        }
    }

    /// <summary>AHK v2 double-quoted string literal.</summary>
    private static string Str(string s) => "\"" + s.Replace("`", "``").Replace("\"", "`\"").Replace("\r", "`r").Replace("\n", "`n") + "\"";
}
